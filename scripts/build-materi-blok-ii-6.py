"""Build data/materi-blok2.6.js from content/materi-blok-ii-6/.

Usage (from JStudyC):  python3 -I scripts/build-materi-blok-ii-6.py

Inputs
  content/materi-blok-ii-6/units.json        unit list (code, title, dept, lecturers)
  content/materi-blok-ii-6/<CODE>.md         summary in Markdown (code with spaces -> '-')
  content/materi-blok-ii-6/<CODE>.quiz.json  10 cumex-style questions
Output
  data/materi-blok2.6.js — registers MATERI_DATA["blok-ii-6"] and, when
  QUESTION_DATA is loaded, QUESTION_DATA["materi-blok-ii-6"] so quiz.js can
  run each unit's quiz and save progress like any other package.
Units without a Markdown file are listed as "segera hadir".
"""
import json
import os
import re
import sys

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), '..'))
CONTENT = os.path.join(ROOT, 'content', 'materi-blok-ii-6')
OUT = os.path.join(ROOT, 'data', 'materi-blok2.6.js')

QUIZ_BLOCK = 'materi-blok-ii-6'
QUIZ_EXAM = 'latihan'
QUIZ_YEAR = 'Latihan'
KINDS = {'EL': 'Expert Lecture', 'IS': 'Integrated Seminar', 'PD': 'Panel Discussion', 'PS': 'Practical Session'}


def slug(code):
    return re.sub(r'[^a-z0-9]+', '-', code.lower()).strip('-')


def file_stem(code):
    return code.replace(' ', '-')


def fail(msg):
    sys.exit(f'build-materi: {msg}')


def main():
    with open(os.path.join(CONTENT, 'units.json'), encoding='utf8') as f:
        meta = json.load(f)

    units, quiz_types = [], {}
    for u in meta['units']:
        code = u['code']
        stem = file_stem(code)
        md_path = os.path.join(CONTENT, stem + '.md')
        quiz_path = os.path.join(CONTENT, stem + '.quiz.json')
        unit = {
            'code': code,
            'slug': slug(code),
            'kind': KINDS[code.split()[0]],
            'title': u['title'],
            'dept': u['dept'],
            'lecturers': u.get('lecturers', []),
            'practical': bool(u.get('practical')),
            'available': os.path.exists(md_path),
        }
        if unit['available']:
            with open(md_path, encoding='utf8') as f:
                unit['markdown'] = f.read()
            for img in re.findall(r'!\[[^\]]*\]\(([^)]+)\)', unit['markdown']):
                if not os.path.exists(os.path.join(ROOT, img)):
                    fail(f'{code}: missing image {img}')
        if os.path.exists(quiz_path):
            with open(quiz_path, encoding='utf8') as f:
                raw = json.load(f)
            questions = []
            for i, q in enumerate(raw, 1):
                if len(q['options']) != 5 or not 0 <= q['correctAnswer'] < 5:
                    fail(f'{code} q{i}: need 5 options and a valid correctAnswer')
                if q.get('image') and not os.path.exists(os.path.join(ROOT, q['image'])):
                    fail(f'{code} q{i}: missing image {q["image"]}')
                item = {
                    'id': i,
                    'source': f'Latihan Materi {code}',
                    'lecture': f'{code} — {u["title"]}',
                    'lectureCode': code,
                    'question': q['question'],
                    'options': q['options'],
                    'correctAnswer': q['correctAnswer'],
                    'explanation': q['explanation'],
                    'answerProvenance': 'ai-generated',
                }
                if q.get('image'):
                    item['image'] = q['image']
                questions.append(item)
            unit['quiz'] = {'block': QUIZ_BLOCK, 'exam': QUIZ_EXAM, 'type': unit['slug'],
                            'year': QUIZ_YEAR, 'count': len(questions)}
            quiz_types[unit['slug']] = {'name': f'{code} — {u["title"]}', 'years': {QUIZ_YEAR: questions}}
        units.append(unit)

    materi = {'id': meta['blockId'], 'name': meta['name'], 'fullName': meta['fullName'], 'units': units}
    quiz_block = {
        'id': QUIZ_BLOCK, 'name': f'Materi {meta["name"]}', 'fullName': meta['fullName'],
        'exams': {QUIZ_EXAM: {'name': 'Latihan per Lecture', 'types': quiz_types}},
    }
    dump = lambda o: json.dumps(o, ensure_ascii=False, indent=2)
    js = (
        '/* Generated by scripts/build-materi-blok-ii-6.py — do not edit by hand. */\n'
        '(function () {\n'
        f'  var materi = {dump(materi)};\n'
        f'  var quiz = {dump(quiz_block)};\n'
        '  window.MATERI_DATA = window.MATERI_DATA || {};\n'
        f'  window.MATERI_DATA[{json.dumps(meta["blockId"])}] = materi;\n'
        f'  if (typeof QUESTION_DATA !== "undefined") QUESTION_DATA[{json.dumps(QUIZ_BLOCK)}] = quiz;\n'
        '})();\n'
    )
    with open(OUT, 'w', encoding='utf8') as f:
        f.write(js)
    done = sum(u['available'] for u in units)
    total_q = sum(len(t['years'][QUIZ_YEAR]) for t in quiz_types.values())
    print(f'{OUT}: {done}/{len(units)} units, {total_q} questions')


if __name__ == '__main__':
    main()
