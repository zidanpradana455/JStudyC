const fs = require('fs');
const path = require('path');

const appRoot = path.resolve(__dirname, '..');
const bankDir = path.resolve(appRoot, '..', 'Bank Soal');
const types = {};

for (const [type, name, filename] of [
  ['reguler', 'Reguler', 'soal_blok_II5_Reguler_2023_cumex1.json'],
  ['iup', 'IUP', 'soal_blok_II5_IUP_cumex1.json'],
]) {
  const source = JSON.parse(fs.readFileSync(path.join(bankDir, filename), 'utf8'));
  const years = {};
  for (const question of source) {
    if (!question.question || !Array.isArray(question.options) ||
        !Number.isInteger(question.correctAnswer) || question.correctAnswer < 0 ||
        question.correctAnswer >= question.options.length) {
      throw new Error(`Invalid question: ${filename} #${question.id}`);
    }
    const normalized = { ...question };
    if (normalized.image) {
      const sourceImage = path.join(bankDir, normalized.image);
      if (fs.existsSync(sourceImage)) {
        const assetDir = `assets/questions/cumex1-blok2.5-${type}`;
        fs.mkdirSync(path.join(appRoot, assetDir), { recursive: true });
        fs.copyFileSync(sourceImage, path.join(appRoot, assetDir, normalized.image));
        normalized.image = `${assetDir}/${normalized.image}`;
      } else {
        normalized.sourceImage = normalized.image;
        normalized.image = '';
        const note = type === 'iup'
          ? 'The referenced image is not available in this question bank.'
          : 'Gambar yang dirujuk belum tersedia dalam bank soal ini.';
        normalized.question += `\n\n[${note}]`;
        console.warn(`Missing image: ${normalized.sourceImage}`);
      }
    }
    (years[String(question.year)] ||= []).push(normalized);
  }
  types[type] = { name, years };
  for (const [year, questions] of Object.entries(years)) {
    console.log(`${name} ${year}: ${questions.length} questions`);
  }
}

const block = {
  id: 'blok-ii-5',
  name: 'Blok II.5',
  fullName: 'Oedema, Urinary and Metabolic Disorders',
  exams: { 'cumex-1': { name: 'Cumex 1', types } },
};
fs.writeFileSync(path.join(appRoot, 'data', 'cumex1-blok2.5.js'),
  '/* Generated by scripts/generate-blok-ii-5-data.js */\n' +
  `QUESTION_DATA["blok-ii-5"] = ${JSON.stringify(block, null, 2)};\n`);
